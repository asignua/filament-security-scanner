<?php

declare(strict_types=1);

namespace Asignua\FilamentSecurityScanner\Tests\Unit;

use Asignua\FilamentSecurityScanner\Enums\SecurityZoneKind;
use Asignua\FilamentSecurityScanner\Scanning\MatchSubject;
use Asignua\FilamentSecurityScanner\Scanning\Rule;
use Asignua\FilamentSecurityScanner\Scanning\RuleRegistry;
use Asignua\FilamentSecurityScanner\Tests\PureTestCase;

/**
 * The real heuristics registry against two corpora.
 *
 * The second test matters more than the first. Catching a shell you put into the
 * fixtures yourself is easy; catching nothing on minified JS, built CSS, a
 * compiled Blade view and a plain JPEG is the very property for the sake of
 * which an off-the-shelf package was rejected (its `php artisan optimize` produced
 * 100 MEDIUM findings in compiled views).
 *
 * Both corpora are real files: the shells come from a real incident and are
 * defanged, the clean ones are copied from a real project.
 */
final class SecurityHeuristicsCorpusTest extends PureTestCase
{
    private const string FIXTURES = __DIR__.'/../fixtures';

    protected function tearDown(): void
    {
        RuleRegistry::flush();

        parent::tearDown();
    }

    /**
     * @return list<Rule>
     */
    private function obfuscationRules(): array
    {
        return RuleRegistry::load(fresh: true)->forScanner('obfuscation');
    }

    private function subjectFor(string $file, SecurityZoneKind $zone = SecurityZoneKind::Code): MatchSubject
    {
        return MatchSubject::make(
            path: $file,
            zoneKind: $zone,
            base: self::FIXTURES,
            size: (int) filesize($file),
            bytes: (string) file_get_contents($file),
        );
    }

    /**
     * @return list<string>
     */
    private function hits(string $file): array
    {
        $subject = $this->subjectFor($file);
        $hits = [];

        foreach ($this->obfuscationRules() as $rule) {
            if (!$rule->covers($subject)) {
                continue;
            }

            if ($rule->evaluate($subject) !== []) {
                $hits[] = $rule->id;
            }
        }

        return $hits;
    }

    public function test_the_registry_loads_without_issues(): void
    {
        $set = RuleRegistry::load(fresh: true);

        $this->assertSame([], $set->issues, 'the package registry must load without a single rejected heuristic');
        $this->assertGreaterThan(0, $set->count());
    }

    /**
     * @return array<string, array{0: string}>
     */
    public static function maliciousProvider(): array
    {
        return [
            'Composer\\Compiler wrapper with gzinflate' => ['halt-compiler-gzinflate.fixture'],
            'JPEG polyglot with PHP in EXIF' => ['jpeg-polyglot-exif.fixture'],
            // The PHP opening tag is case-insensitive, and `<?=` always works
            // (short_open_tag does not disable it). A media disk is mostly webp/avif.
            'GIF polyglot with uppercase <?PHP' => ['gif-polyglot-uppercase-php.fixture'],
            'JPEG polyglot with short tag <?=' => ['jpeg-polyglot-short-echo.fixture'],
            'WEBP polyglot' => ['webp-polyglot.fixture'],
            'AVIF polyglot' => ['avif-polyglot.fixture'],
        ];
    }

    #[\PHPUnit\Framework\Attributes\DataProvider('maliciousProvider')]
    public function test_each_malicious_fixture_is_caught(string $name): void
    {
        $hits = $this->hits(self::FIXTURES.'/malicious/'.$name);

        $this->assertNotEmpty($hits, sprintf('sample "%s" was not caught by any rule', $name));
    }

    /**
     * A clean JPEG with a .php extension is a target of the STRUCTURAL scanner, not
     * of obfuscation. The thumbnail in the incident was generated by the CMS itself:
     * GD stripped the payload, the extension stayed. If obfuscation fired on it, that
     * would mean the rule catches any image.
     */
    public function test_a_clean_jpeg_with_a_php_extension_is_not_an_obfuscation_finding(): void
    {
        $hits = $this->hits(self::FIXTURES.'/malicious/clean-jpeg-with-php-extension.fixture');

        $this->assertSame([], $hits);
    }

    /**
     * But the structural rule must catch it, by extension.
     */
    public function test_the_same_file_is_caught_by_the_structural_rule(): void
    {
        $rule = RuleRegistry::load(fresh: true)->get('uploads.executable-extension');
        $this->assertNotNull($rule);

        $subject = MatchSubject::make('files/12/thumbs/baal.php', SecurityZoneKind::UploadWeb);

        $this->assertTrue($rule->covers($subject));
        $this->assertNotEmpty($rule->evaluate($subject));
        $this->assertTrue($rule->deterministic, 'this rule is entitled to auto-quarantine');
    }

    /**
     * @return array<string, array{0: string}>
     */
    public static function cleanProvider(): array
    {
        return [
            'minified JS from a build' => ['minified-js.fixture'],
            'built CSS' => ['built-css.fixture'],
            'compiled Blade view' => ['compiled-blade.fixture'],
            'plain JPEG' => ['plain-jpeg.fixture'],
            // `<?=` is three bytes and occurs by itself in compressed image data
            // (11 in 81 thousand media-disk files), and the noise after it may contain
            // a backtick and `$_` too. Without a continuous printable tail after the
            // PHP marker this is not a finding, otherwise a media disk would give a
            // dozen criticals.
            'PNG whose noise bytes happen to form <?=' => ['png-with-short-tag-noise.fixture'],
            'real package class' => ['real-php-class.fixture'],
        ];
    }

    #[\PHPUnit\Framework\Attributes\DataProvider('cleanProvider')]
    public function test_no_clean_fixture_produces_a_finding(string $name): void
    {
        $hits = $this->hits(self::FIXTURES.'/clean/'.$name);

        $this->assertSame([], $hits, sprintf('false positive on "%s": %s', $name, implode(', ', $hits)));
    }

    /**
     * No rule of the obfuscation scanner may carry deterministic, otherwise the
     * heuristic would gain the right to move other people's files. The validator
     * already forbids this, but a check over the WHOLE real registry also catches
     * a future rules update.
     */
    public function test_no_obfuscation_rule_may_auto_quarantine(): void
    {
        foreach ($this->obfuscationRules() as $rule) {
            $this->assertFalse($rule->deterministic, $rule->id);
        }
    }

    /**
     * Every rule refers to a translation key, not a literal. An untranslated
     * key is rendered literally in the panel ("security-scanner::rules.Something"),
     * so a missing key in even one locale is a visible defect, not a
     * trifle. We check
     * by reading the files directly: the lightweight container of the package suite
     * has no translator, and `__()` is unavailable here.
     */
    public function test_every_rule_message_exists_in_every_locale(): void
    {
        $missing = [];

        foreach (['de', 'en', 'es', 'fr', 'it', 'nl', 'pl', 'pt_BR', 'tr', 'uk'] as $locale) {
            /** @var array<string, string> $strings */
            $strings = require __DIR__.'/../../resources/lang/'.$locale.'/rules.php';

            foreach (RuleRegistry::load(fresh: true)->all() as $rule) {
                $prefix = 'security-scanner::rules.';
                $key = str_starts_with($rule->message, $prefix) ? substr($rule->message, strlen($prefix)) : $rule->message;

                if ($key !== '' && !array_key_exists($key, $strings)) {
                    $missing[] = $locale.': '.$rule->message.' ('.$rule->id.')';
                }
            }
        }

        $this->assertSame([], $missing);
    }

    /**
     * Regexes must TERMINATE on large input. The config validator does not catch
     * this: it runs preg_match on an empty string, i.e. it checks syntax,
     * not catastrophic backtracking.
     */
    public function test_every_rule_terminates_on_a_large_input(): void
    {
        $haystack = str_repeat("<?php \$a = 'x'.'y'.'z'; eval(base64_decode(\$a)); ", 20000);
        $subject = MatchSubject::make('big.php', SecurityZoneKind::Code, bytes: $haystack);

        $started = microtime(true);

        foreach ($this->obfuscationRules() as $rule) {
            $rule->evaluate($subject);
        }

        $this->assertLessThan(5.0, microtime(true) - $started, 'the registry did not process 1 MB within 5 s');
    }
}
